#!/usr/bin/env python3
"""Regenerate site/BUILDS-INDEX.txt from verification/site backups.

  python3 scripts/site_index.py
"""
import json
from pathlib import Path

from site_kit import OUT, ROOT


def main():
    """Write BUILDS-INDEX.txt and print it.

    @returns: None
    """
    rows = []
    for f in sorted(OUT.glob('*-backup.json'), key=lambda f: json.loads(f.read_text()).get('time', '')):
        name = f.name[:-len('-backup.json')]
        b = json.loads(f.read_text())
        cells = OUT / f'{name}-cells.json'
        res = OUT / f'{name}-result.json'
        n = len(json.loads(cells.read_text())) if cells.exists() else '?'
        mm = json.loads(res.read_text()).get('mismatches', '?') if res.exists() else '?'
        rows.append(
            f"{b.get('time', '?'):19}  {name:24} cells {str(n):>6}  mismatches {mm:>3}  "
            f"box {tuple(b['from'])}..{tuple(b['to'])}  backup {b['structure']}"
        )
    body = '\n'.join(rows) if rows else '(no builds yet)'
    text = (
        'SOUTHAMPTON REFINE — BUILD INDEX (generated by scripts/site_index.py; do not edit)\n'
        'Undo any build by loading its backup structure at the box origin.\n\n'
        + body + '\n'
    )
    (ROOT / 'site/BUILDS-INDEX.txt').write_text(text)
    print(text)


if __name__ == '__main__':
    main()
