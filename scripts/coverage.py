# --- geometry -----------------------------------------------------------------------------
def cell_of(x: int, z: int) -> tuple[int, int]:
    """128-cell key of a column (same grid as COVERAGE.txt and sparse mc_tiles).

    @param x: MC block x
    @param z: MC block z
    @returns: (tx, tz) = (floor(x / 128), floor(z / 128))
    """
    return x // CELL, z // CELL


def cell_bbox(tx0: int, tz0: int, tx1: int, tz1: int) -> tuple[int, int, int, int]:
    """Inclusive block bbox of a rectangle of 128-cells.

    @param tx0: first cell x
    @param tz0: first cell z
    @param tx1: last cell x (inclusive)
    @param tz1: last cell z (inclusive)
    @returns: (x0, z0, x1, z1) inclusive block bounds
    """
    return tx0 * CELL, tz0 * CELL, (tx1 + 1) * CELL - 1, (tz1 + 1) * CELL - 1


def scan_polygon(rings, bbox):
    """Columns whose centre lies inside a polygon, by even-odd scanline over all rings.

    Same inside test as osm_footprints._inside (holes are inner rings), but one pass per row
    so large umbrella polygons (the campus) stay cheap.

    @param rings: [[(x, z), ...], ...] outer ring first, then holes; MC float coords
    @param bbox: (x0, z0, x1, z1) inclusive clip
    @returns: iterator of (x, z)
    """
    x0, z0, x1, z1 = bbox
    edges = [(a, b) for r in rings for a, b in zip(r, r[1:] + r[:1]) if a[1] != b[1]]
    if not edges:
        return
    zs = [v for (_, az), (_, bz) in edges for v in (az, bz)]
    for z in range(max(z0, math.floor(min(zs))), min(z1, math.ceil(max(zs))) + 1):
        zc = z + 0.5
        xs = sorted(ax + (zc - az) * (bx - ax) / (bz - az)
                    for (ax, az), (bx, bz) in edges if (az > zc) != (bz > zc))
        for a, b in zip(xs[::2], xs[1::2]):
            for x in range(max(x0, math.ceil(a - 0.5)), min(x1, math.ceil(b - 0.5) - 1) + 1):
                yield x, z


def line_band(pts, half: float, bbox):
    """Columns whose centre is within `half` of a polyline.

    @param pts: [(x, z), ...] MC float coords
    @param half: band half-width in blocks
    @param bbox: (x0, z0, x1, z1) inclusive clip
    @returns: iterator of (x, z, distance); a column may repeat once per nearby segment
    """
    x0, z0, x1, z1 = bbox
    for a, b in zip(pts, pts[1:]):
        for x in range(max(x0, math.floor(min(a[0], b[0]) - half)), min(x1, math.ceil(max(a[0], b[0]) + half)) + 1):
            for z in range(max(z0, math.floor(min(a[1], b[1]) - half)),
                           min(z1, math.ceil(max(a[1], b[1]) + half)) + 1):
                d = _seg_dist((x + 0.5, z + 0.5), a, b)[0]
                if d <= half:
                    yield x, z, d


def encode_runs(cells) -> list:
    """Row run-length encoding of a column set.

    @param cells: iterable of (x, z)
    @returns: [[z, x_first, x_last], ...] sorted by z then x
    """
    rows = {}
    for x, z in cells:
        rows.setdefault(z, []).append(x)
    out = []
    for z in sorted(rows):
        xs = sorted(rows[z])
        start = prev = xs[0]
        for x in xs[1:]:
            if x != prev + 1:
                out.append([z, start, prev])
                start = x
            prev = x
        out.append([z, start, prev])
    return out


def decode_runs(runs) -> set:
    """Inverse of encode_runs.

    @param runs: [[z, x_first, x_last], ...]
    @returns: {(x, z), ...}
    """
    return {(x, z) for z, a, b in runs for x in range(a, b + 1)}


def components(cells: set, connect=N4) -> list:
    """Connected components of a column set.

    @param cells: {(x, z), ...}
    @param connect: neighbour offsets (default 4-connected)
    @returns: list of sets, largest first, ties by smallest column
    """
    left, out = set(cells), []
    while left:
        seed = min(left)
        comp, todo = {seed}, deque([seed])
        left.discard(seed)
        while todo:
            x, z = todo.popleft()
            for dx, dz in connect:
                n = (x + dx, z + dz)
                if n in left:
                    left.discard(n)
                    comp.add(n)
                    todo.append(n)
        out.append(comp)
    return sorted(out, key=lambda c: (-len(c), min(c)))


def find_seams(bbox, touched: set, max_width: int = 3) -> list:
    """Untouched strips 1..max_width columns wide with touched columns on both sides.

    Scans every row and every column of bbox; catches slivers between neighbouring builds
    (build-bbox seams) and narrow holes left inside one build.

    @param bbox: (x0, z0, x1, z1) inclusive area to scan
    @param touched: {(x, z)} touched columns
    @param max_width: widest untouched run still reported as a seam
    @returns: 8-connected seam components (list of sets), largest first
    """
    x0, z0, x1, z1 = bbox
    seam = set()
    for z in range(z0, z1 + 1):
        prev = None
        for x in range(x0, x1 + 1):
            if (x, z) in touched:
                if prev is not None and 1 <= x - prev - 1 <= max_width:
                    seam.update((u, z) for u in range(prev + 1, x))
                prev = x
    for x in range(x0, x1 + 1):
        prev = None
        for z in range(z0, z1 + 1):
            if (x, z) in touched:
                if prev is not None and 1 <= z - prev - 1 <= max_width:
                    seam.update((x, u) for u in range(prev + 1, z))
                prev = z
    n8 = tuple((dx, dz) for dx in (-1, 0, 1) for dz in (-1, 0, 1) if dx or dz)
    return components(seam, n8)


# --- OSM classification -------------------------------------------------------------------
def osm_ref(p: dict) -> str:
    """Stable OSM reference of a feature: 'w<way id>' or 'r<relation id>'.

    @param p: feature properties (polygon layers carry osm_way_id or osm_id; lines osm_id)
    @returns: e.g. 'w23456789'
    """
    if p.get('osm_way_id'):
        return 'w' + str(p['osm_way_id'])
    if p.get('highway') and p.get('osm_id') and 'z_order' in p:
        return 'w' + str(p['osm_id'])
    return 'r' + str(p.get('osm_id'))


def property_label(p: dict) -> str:
    """Human label of a building: '<addr:street> <number>', else its name, else its tag.

    @param p: building feature properties
    @returns: label string
    """
    num, street = _addr(p)
    if num or street:
        return f'{street or "?"} {num or ""}'.strip()
    return p.get('name') or f'building={p.get("building")} {osm_ref(p)}'


def grows_garden(p: dict) -> bool:
    """Whether a building seeds a garden plot (homes and addressed non-institutional buildings).

    @param p: building feature properties
    @returns: True for houses / flats / addressed shops; False for campus blocks, sheds...
    """
    b = p.get('building')
    if b in OUTBUILDINGS or b in INSTITUTIONS:
        return False
    return b in HOMES or bool(_addr(p)[0])


def area_kind(t: dict):
    """Classify a non-building polygon.

    @param t: flattened tags (osm_tags)
    @returns: 'umbrella', 'path', 'open', or None (ignored: no ground-cover tag)
    """
    if any(t.get(k) in v for k, v in UMBRELLA.items()):
        return 'umbrella'
    if t.get('highway') in ('pedestrian', 'footway', 'path', 'cycleway'):
        return 'path'
    if any(t.get(k) for k in OPEN_KEYS):
        return 'open'
    return None


def area_label(t: dict, ref: str) -> str:
    """Label of an open / umbrella polygon: name plus its main tag.

    @param t: flattened tags
    @param ref: osm_ref of the polygon
    @returns: e.g. 'Highfield Campus (amenity=university)'
    """
    tag = next((f'{k}={t[k]}' for k in OPEN_KEYS if t.get(k)), ref)
    return f'{t["name"]} ({tag})' if t.get('name') else f'{tag} {ref}'


# --- building the parcel map --------------------------------------------------------------
class ParcelBuilder:
    """Assign every column of an area (+ MARGIN) to exactly one parcel.

    Order: footprints > highways (best score, nearest) > open polygons (smallest first) >
    gardens grown from home footprints (+ leftover outbuildings) > street-surface fringe >
    residual gaps / no_osm.
    """

    def __init__(self, name: str, cells, idx: OSMIndex | None = None, pristine: World | None = None):
        """@param name: area name
        @param cells: (tx0, tz0, tx1, tz1) inclusive 128-cell rectangle
        @param idx: OSMIndex (loaded if omitted)
        @param pristine: World over the untouched Geocraft save (street surface for growth)
        """
        self.name = name
        self.cells = tuple(cells)
        self.core = cell_bbox(*self.cells)
        x0, z0, x1, z1 = self.core
        self.grid = (x0 - MARGIN, z0 - MARGIN, x1 + MARGIN, z1 + MARGIN)
        self.idx = idx or OSMIndex()
        self.pristine = pristine or World(PRISTINE)
        self.owner = {}       # (x, z) -> parcel id
        self.parcels = {}     # parcel id -> {'kind', 'label', 'meta'}
        self.outbuildings = {}
        self.seeds = {}
        self.umbrellas = []   # (label, set of columns)
        self._surf = {}

    def in_grid(self, x: int, z: int) -> bool:
        """@returns: whether (x, z) lies in the working grid (area + margin)"""
        x0, z0, x1, z1 = self.grid
        return x0 <= x <= x1 and z0 <= z <= z1

    def in_core(self, x: int, z: int) -> bool:
        """@returns: whether (x, z) lies in the area's own cells"""
        x0, z0, x1, z1 = self.core
        return x0 <= x <= x1 and z0 <= z <= z1

    def _register(self, pid: str, kind: str, label: str, **meta):
        self.parcels.setdefault(pid, {'kind': kind, 'label': label, 'meta': meta})

    def footprints(self):
        """OSM building footprints -> property parcels (outbuildings held back as absorbable)."""
        for (x, z), i in self.idx.cells().items():
            if not self.in_grid(x, z):
                continue
            p = self.idx.buildings[i][1]
            pid = 'prop:' + osm_ref(p)
            self._register(pid, 'property', property_label(p), building=p.get('building'),
                           grows=grows_garden(p))
            if p.get('building') in OUTBUILDINGS:
                self.outbuildings[(x, z)] = pid
                continue
            self.owner[(x, z)] = pid
            if grows_garden(p):
                self.seeds[(x, z)] = pid

    def highways(self):
        """Road and path corridors at Geocraft's fixed half-widths; per-cell parcels."""
        best = {}
        for (name, hw, pts), p in zip(self.idx.streets, self.idx.street_props):
            t = osm_tags(p)
            if hw in NOT_GROUND or t.get('tunnel', 'no') != 'no' or _layer(t) < 0:
                continue
            kind, bands = WAY_BANDS.get(hw, _ROAD)
            ref = osm_ref(p)
            base = name if kind == 'road' and name else ref
            label = name or f'highway={hw} {ref}'
            for half, score in bands:
                for x, z, d in line_band(pts, half, self.grid):
                    if (x, z) in self.owner or (x, z) in self.outbuildings:
                        continue
                    key = (score, -d)
                    cur = best.get((x, z))
                    if cur is None or key > cur[0]:
                        best[(x, z)] = (key, kind, base, label, hw)
        for (x, z), (_k, kind, base, label, hw) in best.items():
            tx, tz = cell_of(x, z)
            pid = f'{kind}:{base}@{tx},{tz}'
            self.owner[(x, z)] = pid
            self._register(pid, kind, label, highway=hw, cell=[tx, tz])

    def areas(self):
        """Open polygons -> per-cell open/path parcels (smallest polygon wins); umbrellas kept."""
        merged = {}
        for rings, p in self.idx.areas:
            t = osm_tags(p)
            kind = area_kind(t)
            if not kind:
                continue
            ref = osm_ref(p)
            m = merged.setdefault(ref, [kind, area_label(t, ref), set()])
            m[2].update(scan_polygon(rings, self.grid))
        for ref, (kind, label, cells) in sorted(merged.items(), key=lambda kv: (len(kv[1][2]), kv[0])):
            if kind == 'umbrella':
                if cells:
                    self.umbrellas.append((label, cells))
                continue
            for x, z in sorted(cells):
                if (x, z) in self.owner or (x, z) in self.outbuildings:
                    continue
                tx, tz = cell_of(x, z)
                pid = f'{kind}:{ref}@{tx},{tz}'
                self.owner[(x, z)] = pid
                self._register(pid, kind, label, osm=ref, cell=[tx, tz])

    def street(self, x: int, z: int) -> bool:
        """@returns: whether the pristine Geocraft surface of (x, z) is road / pavement (cached)"""
        if (x, z) not in self._surf:
            self._surf[(x, z)] = street_surface(self.pristine, x, z)
        return self._surf[(x, z)]

    def gardens(self):
        """Grow home footprints over unassigned ground until street surface (pristine) or a neighbour."""
        def passable(x, z):
            return self.in_grid(x, z) and (x, z) not in self.owner and not self.street(x, z)
        for c, pid in grow_plots(self.seeds, passable, REACH).items():
            self.owner.setdefault(c, pid)
        for c, pid in self.outbuildings.items():
            self.owner.setdefault(c, pid)

    def fringe(self):
        """Stock street surface just past the fixed corridors joins the parcel it touches.

        Geocraft's real raster has junction caps, driveway mouths and paved verges beyond the
        fixed half-widths; left alone they become hundreds of 1-5 column gaps. Up to FRINGE
        blocks deep they join the touching road / path parcel, else the touching property, so
        they still count against that parcel's 100%.
        """
        for kinds in (('road', 'path'), ('property', 'open')):
            todo = deque()
            for (x, z), pid in sorted(self.owner.items()):
                if self.parcels[pid]['kind'] in kinds:
                    todo.append((x, z, pid, 0))
            while todo:
                x, z, pid, d = todo.popleft()
                if d >= FRINGE:
                    continue
                for dx, dz in N4:
                    n = (x + dx, z + dz)
                    if self.in_grid(*n) and n not in self.owner and self.street(*n):
                        self.owner[n] = pid
                        todo.append((n[0], n[1], pid, d + 1))

    def residual(self):
        """Unassigned columns -> gap components per cell, or no_osm outside every OSM clip.

        Components of at most SLIVER columns are raster slivers between parcels (e.g. Geocraft
        carpet fringe just outside a footprint); they join the neighbour sharing the longest
        edge (property on ties) and count against its 100%, instead of becoming parcels.
        """
        x0, z0, x1, z1 = self.grid
        left = {(x, z) for x in range(x0, x1 + 1) for z in range(z0, z1 + 1) if (x, z) not in self.owner}
        by_cell = {}
        for x, z in left:
            if not self.idx.covered(x, z):
                tx, tz = cell_of(x, z)
                pid = f'no_osm@{tx},{tz}'
                self.owner[(x, z)] = pid
                self._register(pid, 'no_osm', f'no OSM clip in cell {tx},{tz}', cell=[tx, tz])
            else:
                by_cell.setdefault(cell_of(x, z), set()).add((x, z))
        slivers = []
        for (tx, tz), cells in sorted(by_cell.items()):
            for comp in components(cells):
                if len(comp) <= SLIVER:
                    slivers.append(comp)
                    continue
                gx, gz = min(comp)
                pid = f'gap:{gx},{gz}'
                for c in comp:
                    self.owner[c] = pid
                self._register(pid, 'gap', pid, cell=[tx, tz])
        for comp in slivers:
            nb = Counter(self.owner[n] for x, z in comp for dx, dz in N4
                         if (n := (x + dx, z + dz)) in self.owner)
            if not nb:
                gx, gz = min(comp)
                pid = f'gap:{gx},{gz}'
                self._register(pid, 'gap', pid, cell=list(cell_of(gx, gz)))
            else:
                pid = max(nb, key=lambda o: (nb[o], self.parcels[o]['kind'] == 'property', o))
            for c in comp:
                self.owner[c] = pid

    def name_gaps(self, members: dict):
        """Label each gap 'gap:x,z N cols, between <A> and <B>[, edge of <umbrella>]'.

        @param members: {parcel id: set of columns}
        """
        for pid, cells in members.items():
            info = self.parcels[pid]
            if info['kind'] != 'gap':
                continue
            nb = Counter()
            edge, within = set(), set()
            for x, z in cells:
                for dx, dz in N4:
                    o = self.owner.get((x + dx, z + dz))
                    if o and o != pid and self.parcels[o]['kind'] not in GAPLIKE:
                        nb[o] += 1
            for label, ucells in self.umbrellas:
                inside = [c in ucells for c in cells]
                if any(inside):
                    within.add(label)
                if any(((x, z) in ucells) != ((x + dx, z + dz) in ucells)
                       for x, z in cells for dx, dz in N4):
                    edge.add(label)
            names = [self.parcels[o]['label'] for o, _n in nb.most_common(2)]
            text = f'{pid} {len(cells)} cols, ' + (
                f'between {names[0]} and {names[1]}' if len(names) == 2 else
                f'beside {names[0]}' if names else 'isolated')
            if edge:
                text += ', edge of ' + ' / '.join(sorted(edge))
            elif within:
                text += ', in ' + ' / '.join(sorted(within))
            info['label'] = text
            info['meta'].update(neighbours=[o for o, _n in nb.most_common(4)], edge_of=sorted(edge),
                                within=sorted(within))

    def run(self) -> dict:
        """Build the whole map.

        @returns: JSON-ready area record (see save_area)
        """
        self.footprints()
        self.highways()
        self.areas()
        self.gardens()
        self.fringe()
        self.residual()
        members = {}
        for c, pid in self.owner.items():
            members.setdefault(pid, set()).add(c)
        keep = {pid: cs for pid, cs in members.items() if any(self.in_core(*c) for c in cs)}
        self.name_gaps(keep)
        x0, z0, x1, z1 = self.grid
        core_cols = (self.core[2] - self.core[0] + 1) * (self.core[3] - self.core[1] + 1)
        assigned = sum(1 for cs in keep.values() for c in cs if self.in_core(*c))
        if assigned != core_cols:
            raise RuntimeError(f'{self.name}: {assigned} core columns assigned, expected {core_cols}')
        out = []
        for pid, cs in keep.items():
            info = self.parcels[pid]
            meta = dict(info['meta'])
            if info['kind'] == 'property':
                meta['clipped'] = any(x in (x0, x1) or z in (z0, z1) for x, z in cs)
            out.append({'id': pid, 'kind': info['kind'], 'label': info['label'], 'n': len(cs),
                        'bbox': [min(x for x, _ in cs), min(z for _, z in cs),
                                 max(x for x, _ in cs), max(z for _, z in cs)],
                        'digest': digest(cs), 'meta': meta, 'runs': encode_runs(cs)})
        out.sort(key=lambda p: (KINDS.index(p['kind']), p['id']))
        return {'area': self.name, 'cells': list(self.cells), 'core': list(self.core),
                'grid': list(self.grid), 'built': datetime.now().strftime('%Y-%m-%d %H:%M'),
                'reach': REACH, 'umbrellas': sorted(label for label, _c in self.umbrellas),
                'parcels': out}


def _layer(t: dict) -> int:
    try:
        return int(t.get('layer', 0))
    except ValueError:
        return 0


def digest(cells) -> str:
    """Short geometry fingerprint of a parcel (to spot sign-offs on a parcel that later moved).

    @param cells: iterable of (x, z)
    @returns: 12-hex-digit sha1 of the run encoding
    """
    return hashlib.sha1(json.dumps(encode_runs(cells)).encode()).hexdigest()[:12]


