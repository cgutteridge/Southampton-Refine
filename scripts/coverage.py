def cmd_build(args) -> int:
    """Rebuild one or every area's parcel register, then COVERAGE.txt.

    @param args: argparse namespace (area, cells, note)
    @returns: exit code
    """
    if args.cells:
        if not args.area:
            raise SystemExit('--cells needs --area')
        save_area_spec(args.area, args.cells, args.note)
    specs = load_area_specs()
    names = [args.area] if args.area else list(specs)
    if not names or any(n not in specs for n in names):
        raise SystemExit(f'unknown area(s) {names}; add with: build --area NAME --cells tx0,tz0,tx1,tz1')
    idx, pristine = OSMIndex(), World(PRISTINE)
    for n in names:
        rec = ParcelBuilder(n, specs[n]['cells'], idx, pristine).run()
        path = save_area(rec)
        kinds = Counter(p['kind'] for p in rec['parcels'])
        print(f'{n}: {len(rec["parcels"])} parcels ' +
              ', '.join(f'{k} {kinds[k]}' for k in KINDS if kinds[k]) + f' -> {path.relative_to(ROOT)}')
    write_coverage()
    print(f'updated {COVERAGE_TXT.relative_to(ROOT)} PROCESSED CELLS')
    return 0


def _parcel_line(p: dict, s: dict) -> str:
    flag = ' SIGNOFF-LAPSED' if s['lapsed'] else ' moved-since-signoff' if s['moved'] else ''
    return (f'{p["id"]} | {p["kind"]} | {s["state"]} {pct(s["t"], s["n"])} ({s["t"]}/{s["n"]}){flag} | '
            f'{p["label"]}')


def _detail(area: Area, pid: str, by_build: dict, touched: set, signoffs: dict):
    p = area.parcels[pid]
    s = stats(area, touched, signoffs)[pid]
    print(_parcel_line(p, s))
    print(f'  area {area.name}  bbox {p["bbox"]}  digest {p["digest"]}  meta {p["meta"]}')
    who = Counter({b: len(cols & p['set']) for b, cols in by_build.items() if cols & p['set']})
    print('  touched by: ' + (', '.join(f'{b} {n}' for b, n in who.most_common()) or '(nothing)'))
    miss = sorted(p['set'] - touched)
    if miss:
        print(f'  untouched {len(miss)} columns, e.g. {miss[:10]}')
    if pid in signoffs:
        print(f'  sign-off: {signoffs[pid]}')


def cmd_status(args) -> int:
    """Summary per area, optional filtered parcel list, parcel detail and Geocraft check.

    @param args: argparse namespace
    @returns: exit code (1 if --check finds leftover Geocraft in done parcels)
    """
    by_build = touched_by_build()
    touched, signoffs = union(by_build), load_signoffs()
    bad = 0
    for a in load_areas(args.area):
        st = stats(a, touched, signoffs)
        if args.parcel:
            if args.parcel in a.parcels:
                _detail(a, args.parcel, by_build, touched, signoffs)
            continue
        print(f'== {a.name}: cells {a.cells[0]}..{a.cells[2]} x {a.cells[1]}..{a.cells[3]}, '
              f'built {a.built}, {len(a.parcels)} parcels')
        print(f'  {"kind":9} {"parcels":>7} {"untouched":>9} {"touched":>7} {"done":>5} {"columns":>8} {"touched%":>8}')
        for k in KINDS + ('all',):
            ps = [pid for pid, p in a.parcels.items() if k in ('all', p['kind'])]
            if not ps:
                continue
            c = Counter(st[p]['state'] for p in ps)
            n = sum(st[p]['n'] for p in ps)
            t = sum(st[p]['t'] for p in ps)
            print(f'  {k:9} {len(ps):7} {c["untouched"]:9} {c["touched"]:7} {c["done"]:5} {n:8} {pct(t, n):>8}')
        lapsed = [pid for pid in a.parcels if st[pid]['lapsed']]
        if lapsed:
            print(f'  {len(lapsed)} sign-offs lapsed below 100%: {lapsed[:8]}')
        sel = list(a.parcels)
        if args.cell:
            tx, tz = (int(v) for v in args.cell.split(','))
            sel = [pid for pid in sel if any(cell_of(*c) == (tx, tz) for c in a.parcels[pid]['set'])]
        if args.kind:
            sel = [pid for pid in sel if a.parcels[pid]['kind'] == args.kind]
        if args.state:
            sel = [pid for pid in sel if st[pid]['state'] == args.state]
        if args.list or args.cell or args.kind or args.state:
            sel.sort(key=lambda pid: (-st[pid]['pct'], -st[pid]['n']))
            for pid in sel[:args.limit]:
                print('  ' + _parcel_line(a.parcels[pid], st[pid]))
            if len(sel) > args.limit:
                print(f'  ... {len(sel) - args.limit} more (raise --limit)')
        if args.check:
            live, pristine = World(), World(PRISTINE)
            done = [p for p in a.parcels if st[p]['state'] == 'done']
            placed = placed_heights((c for p in done for c in a.parcels[p]['set']), by_build)
            for pid in done:
                hits = geocraft_leftovers(a.parcels[pid]['set'], a.parcels[pid]['kind'], live, pristine,
                                          placed)
                if any(hits.values()):
                    bad += 1
                    print(f'  LEFTOVER GEOCRAFT in done {pid}: ' +
                          ', '.join(f'{k} {len(v)} e.g. {v[:2]}' for k, v in hits.items() if v))
            print(f'  geocraft check on done parcels: {bad} with leftovers')
    if args.write:
        write_coverage(by_build=by_build)
        print(f'updated {COVERAGE_TXT.relative_to(ROOT)} PROCESSED CELLS')
    return 1 if bad else 0


def cmd_gaps(args) -> int:
    """Gap / no_osm parcels and seams (narrow untouched strips between touched ground).

    @param args: argparse namespace (area, limit, width)
    @returns: exit code
    """
    by_build = touched_by_build()
    touched, signoffs = union(by_build), load_signoffs()
    for a in load_areas(args.area):
        st = stats(a, touched, signoffs)
        gaps = sorted((pid for pid, p in a.parcels.items() if p['kind'] in GAPLIKE),
                      key=lambda pid: -a.parcels[pid]['n'])
        c = Counter(st[g]['state'] for g in gaps)
        print(f'== {a.name}: {len(gaps)} gap parcels ({c["untouched"]} untouched, {c["touched"]} touched, '
              f'{c["done"]} done), {sum(a.parcels[g]["n"] for g in gaps)} columns')
        for g in gaps[:args.limit]:
            print('  ' + _parcel_line(a.parcels[g], st[g]))
        if len(gaps) > args.limit:
            print(f'  ... {len(gaps) - args.limit} more (raise --limit)')
        seams = find_seams(a.core, touched, args.width)
        own = a.owner()
        print(f'  seams (untouched strips 1-{args.width} wide between touched columns): {len(seams)} strips, '
              f'{sum(len(s) for s in seams)} columns')
        for s in seams[:args.limit]:
            xs, zs = [x for x, _ in s], [z for _, z in s]
            ring = {(x + dx, z + dz) for x, z in s for dx in (-1, 0, 1) for dz in (-1, 0, 1)} - s
            builds = sorted(b for b, cols in by_build.items() if cols & ring)
            parcels = Counter(own[c] for c in s)
            print(f'  seam {len(s)} cols bbox [{min(xs)},{min(zs)},{max(xs)},{max(zs)}] '
                  f'between {", ".join(builds[:3]) or "?"}{" +" if len(builds) > 3 else ""} | in '
                  + ', '.join(f'{pid} ({n})' for pid, n in parcels.most_common(3)))
        if len(seams) > args.limit:
            print(f'  ... {len(seams) - args.limit} more seams')
    return 0


def _find_parcel(areas: list, pid: str):
    return next(((a, a.parcels[pid]) for a in areas if pid in a.parcels), (None, None))


def cmd_signoff(args) -> int:
    """Record sign-offs (refused below 100% or on leftover Geocraft), backfill, or revoke.

    @param args: argparse namespace
    @returns: exit code (1 if any requested sign-off was refused)
    """
    areas = load_areas()
    by_build = touched_by_build()
    touched, signoffs = union(by_build), load_signoffs()
    today = args.date or date.today().isoformat()
    if args.revoke:
        if not args.reason:
            raise SystemExit('--revoke needs --reason')
        for pid in args.ids:
            if pid not in signoffs:
                print(f'{pid}: no active sign-off')
                continue
            append_signoff({'parcel': pid, 'revoke': True, 'date': today, 'reason': args.reason})
            print(f'{pid}: sign-off revoked')
        write_coverage(areas, by_build)
        return 0
    live, pristine = World(), World(PRISTINE)
    placed, primed = {}, set()

    def prime(cols):
        todo = set(cols) - primed
        if todo:
            placed.update(placed_heights(todo, by_build))
            primed.update(todo)

    def check(a, p, build):
        cols = p['set']
        t = len(cols & touched)
        if t < p['n']:
            miss = sorted(cols - touched)
            return f'touched {t}/{p["n"]} ({pct(t, p["n"])}) — {len(miss)} untouched, e.g. {miss[:4]}'
        if build is not None:
            if build in REVERTED:
                return f'{build} was reverted (I-009)'
            if build not in by_build:
                return f'no verification/site/{build}-cells.json'
            if not by_build[build] & cols:
                return f'{build} touched none of its columns'
        prime(cols)
        hits = geocraft_leftovers(cols, p['kind'], live, pristine, placed, limit=20)
        if any(hits.values()):
            return 'leftover Geocraft ' + ', '.join(f'{k} e.g. {v[:2]}' for k, v in hits.items() if v)
        return None

    def sign(a, p, build, note):
        append_signoff({'parcel': p['id'], 'area': a.name, 'build': build, 'date': today,
                        'columns': p['n'], 'digest': p['digest'], 'note': note})

    refused = 0
    if args.backfill:
        builds = [b.strip() for b in args.builds.split(',')] if args.builds else sorted(by_build)
        unknown = [b for b in builds if b not in by_build]
        if unknown:
            raise SystemExit(f'unknown or reverted builds: {unknown}')
        report, seen = {'signed': [], 'already': [], 'short': [], 'refused': []}, set()
        prime(c for a in areas for pid, p in a.parcels.items()
              if pid not in signoffs and p['set'] <= touched
              and any(by_build[b] & p['set'] for b in builds) for c in p['set'])
        for a in areas:
            for pid, p in a.parcels.items():
                if pid in seen:
                    continue
                who = Counter({b: len(by_build[b] & p['set']) for b in builds if by_build[b] & p['set']})
                if not who:
                    continue
                seen.add(pid)
                if pid in signoffs:
                    report['already'].append(pid)
                    continue
                t = len(p['set'] & touched)
                if t < p['n']:
                    report['short'].append((pid, p['kind'], t, p['n'], p['label']))
                    continue
                build = who.most_common(1)[0][0]
                why = check(a, p, build)
                if why:
                    report['refused'].append((pid, why))
                    continue
                if not args.dry_run:
                    sign(a, p, build, args.note or 'Q-038 backfill')
                report['signed'].append((pid, build))
        short = sorted(report['short'], key=lambda r: -r[2] / r[3])
        print(f'backfill over {len(builds)} builds: signed {len(report["signed"])}, already {len(report["already"])}, '
              f'refused (leftover Geocraft) {len(report["refused"])}, short of 100% {len(short)}'
              + (' [dry run]' if args.dry_run else ''))
        by_kind = Counter(r[1] for r in short)
        print('  short by kind: ' + ', '.join(f'{k} {by_kind[k]}' for k in KINDS if by_kind[k]))
        for pid, kind, t, n, label in short[:args.limit]:
            print(f'  SHORT {pid} | {kind} | {pct(t, n)} ({t}/{n}) | {label}')
        for pid, why in report['refused'][:args.limit]:
            print(f'  REFUSED {pid}: {why}')
        STORE.mkdir(parents=True, exist_ok=True)
        rep = STORE / f'backfill-{today}{"-dry" if args.dry_run else ""}.json'
        rep.write_text(json.dumps(report, indent=1, ensure_ascii=False))
        print(f'  full report: {rep.relative_to(ROOT)}')
    else:
        if not args.ids or not args.build:
            raise SystemExit('signoff needs parcel ids and --build (or --backfill / --revoke)')
        for pid in args.ids:
            a, p = _find_parcel(areas, pid)
            if p is None:
                print(f'REFUSED {pid}: no such parcel (coverage.py status --list)')
                refused += 1
                continue
            why = check(a, p, args.build)
            if why:
                print(f'REFUSED {pid}: {why}')
                refused += 1
                continue
            if args.dry_run:
                print(f'would sign {pid} ({p["label"]}) by {args.build} on {today} [dry run]')
                continue
            sign(a, p, args.build, args.note)
            print(f'signed {pid} ({p["label"]}) by {args.build} on {today}')
    if not args.dry_run:
        write_coverage(areas, by_build)
    return 1 if refused else 0


def cmd_map(args) -> int:
    """PNG map per area: colour by state, gaps hatched red, seams magenta, cell grid.

    @param args: argparse namespace (area, out)
    @returns: exit code
    """
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        from matplotlib.patches import Patch
        import numpy as np
    except ImportError:
        raise SystemExit('map needs numpy + matplotlib: .venv/bin/python scripts/coverage.py map')
    by_build = touched_by_build()
    touched, signoffs = union(by_build), load_signoffs()
    base = {'property': (0.86, 0.86, 0.86), 'road': (0.66, 0.68, 0.74), 'path': (0.78, 0.78, 0.84),
            'open': (0.82, 0.88, 0.82), 'gap': (0.95, 0.93, 0.90), 'no_osm': (0.55, 0.55, 0.55)}
    done_c, red, seam_c = np.array((0.18, 0.62, 0.28)), np.array((0.85, 0.08, 0.08)), np.array((0.9, 0.0, 0.9))
    for a in load_areas(args.area):
        st = stats(a, touched, signoffs)
        own = a.owner()
        x0, z0, x1, z1 = a.core
        w, h = x1 - x0 + 1, z1 - z0 + 1
        img = np.zeros((h, w, 3))
        for z in range(z0, z1 + 1):
            for x in range(x0, x1 + 1):
                pid = own[(x, z)]
                p, s = a.parcels[pid], st[pid]
                if s['state'] == 'done':
                    c = done_c
                elif s['state'] == 'touched':
                    f = s['pct'] / 100
                    c = np.array((0.95, 0.50 + 0.38 * f, 0.15 + 0.2 * f))
                else:
                    c = np.array(base[p['kind']])
                if s['state'] == 'touched' and (x, z) not in touched:
                    c = 0.5 * c + 0.5
                if p['kind'] in GAPLIKE and (x + z) % 6 < 2:
                    c = red if p['kind'] == 'gap' else red * 0.45
                for dx, dz in N4:
                    if own.get((x + dx, z + dz), pid) != pid:
                        c = c * 0.72
                        break
                img[z - z0, x - x0] = c
        for s in find_seams(a.core, touched):
            for x, z in s:
                img[z - z0, x - x0] = seam_c
        fig, ax = plt.subplots(figsize=(max(8, w / 48), max(8, h / 48) + 1.2), dpi=100)
        ax.imshow(img, extent=(x0 - .5, x1 + .5, z1 + .5, z0 - .5), interpolation='nearest')
        for tx, tz in a.core_cells():
            bx0, bz0, bx1, bz1 = cell_bbox(tx, tz, tx, tz)
            ax.add_patch(plt.Rectangle((bx0 - .5, bz0 - .5), CELL, CELL, fill=False, ls='--', lw=0.8, ec='k'))
            ax.text(bx0 + 3, bz0 + 9, f'{tx},{tz}', fontsize=9, weight='bold')
        c = Counter(st[p]['state'] for p in a.parcels)
        ax.set_title(f'coverage {a.name}: {len(a.parcels)} parcels — done {c["done"]}, touched {c["touched"]}, '
                     f'untouched {c["untouched"]}  (built {a.built})')
        ax.legend(handles=[Patch(color=done_c, label='done (100% + signed off)'),
                           Patch(color=(0.95, 0.88, 0.35), label='touched (redder = lower %; pale = untouched column)'),
                           Patch(color=base['property'], label='untouched property'),
                           Patch(color=base['road'], label='untouched road / path'),
                           Patch(color=base['open'], label='untouched open land'),
                           Patch(color=red, label='gap (hatched red)'),
                           Patch(color=red * 0.45, label='no OSM clip (hatched dark)'),
                           Patch(color=seam_c, label='seam: 1-3 wide untouched strip')],
                  loc='upper center', bbox_to_anchor=(0.5, -0.04), ncol=4, fontsize=8)
        out = Path(args.out) if args.out and args.area else STORE / f'{a.name}-map.png'
        fig.savefig(out, bbox_inches='tight')
        plt.close(fig)
        print(f'{a.name}: {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}')
    return 0


